"""Codegen coverage — graph_json → Qiskit script.

Pure functions, no DB or executor. These are characterization tests: they
pin the script the editor's graphs produce today so a codegen refactor
that changes user-visible output fails loudly instead of silently.
"""

from __future__ import annotations

import ast

import pytest

from src.runner.codegen import (
    GraphCycleError,
    generate_preamble,
    generate_python,
)


def _node(nid: str, ntype: str, **data) -> dict:
    return {"id": nid, "type": ntype, "data": data}


def _edge(src: str, tgt: str) -> dict:
    return {"id": f"{src}-{tgt}", "source": src, "target": tgt}


BELL_GRAPH = {
    "nodes": [
        _node("h", "qiskit.hadamard", qubit_index=0),
        _node("cx", "qiskit.cnot", control_qubit=0, target_qubit=1),
        _node("m0", "qiskit.measure", qubit_index=0, classical_index=0),
        _node("m1", "qiskit.measure", qubit_index=1, classical_index=1),
        _node("run", "qiskit.run_local_simulator", shots=512),
        _node("plot", "qiskit.plot_histogram"),
    ],
    "edges": [
        _edge("h", "cx"),
        _edge("cx", "m0"),
        _edge("m0", "m1"),
        _edge("m1", "run"),
        _edge("run", "plot"),
    ],
    "config": {"num_qubits": 2, "num_classical": 2, "shots": 1000},
}


def test_bell_state_script_is_exact() -> None:
    assert generate_python(BELL_GRAPH) == "\n".join(
        [
            "# Auto-generated by node-forge — do not hand-edit.",
            "from qiskit import QuantumCircuit, transpile",
            "from qiskit_aer import AerSimulator",
            "import matplotlib",
            "matplotlib.use('Agg')",
            "from qiskit.visualization import plot_histogram",
            "",
            "qc = QuantumCircuit(2, 2)",
            "qc.h(0)",
            "qc.cx(0, 1)",
            "qc.measure(0, 0)",
            "qc.measure(1, 1)",
            "",
            "_sim = AerSimulator()",
            "_tqc = transpile(qc, _sim)",
            "_job = _sim.run(_tqc, shots=512)",
            "_counts = _job.result().get_counts()",
            "print('Counts:', _counts)",
            "_fig = plot_histogram(_counts)",
            "_fig.savefig('histogram.png', bbox_inches='tight')",
            "print('Saved histogram.png')",
            "",
        ]
    )


def test_empty_graph_still_emits_valid_python() -> None:
    script = generate_python({})
    ast.parse(script)
    assert "qc = QuantumCircuit(2, 2)" in script
    assert "AerSimulator" not in script
    assert "plot_histogram" not in script


def test_config_values_are_clamped_to_at_least_one() -> None:
    script = generate_python({"config": {"num_qubits": 0, "num_classical": -3}})
    assert "qc = QuantumCircuit(1, 1)" in script


def test_run_without_shots_uses_config_shots() -> None:
    graph = {
        "nodes": [_node("run", "qiskit.run_local_simulator")],
        "config": {"shots": 4096},
    }
    assert "shots=4096" in generate_python(graph)


def test_edges_define_execution_order_not_node_list_order() -> None:
    graph = {
        "nodes": [
            _node("x", "qiskit.pauli_x", qubit_index=1),
            _node("h", "qiskit.hadamard", qubit_index=0),
        ],
        "edges": [_edge("h", "x")],
    }
    script = generate_python(graph)
    assert script.index("qc.h(0)") < script.index("qc.x(1)")


def test_edges_to_unknown_nodes_are_ignored() -> None:
    graph = {
        "nodes": [_node("h", "qiskit.hadamard", qubit_index=0)],
        "edges": [_edge("h", "ghost"), {"source": None, "target": "h"}],
    }
    assert "qc.h(0)" in generate_python(graph)


def test_cycle_raises() -> None:
    graph = {
        "nodes": [
            _node("a", "qiskit.hadamard"),
            _node("b", "qiskit.pauli_x"),
        ],
        "edges": [_edge("a", "b"), _edge("b", "a")],
    }
    with pytest.raises(GraphCycleError):
        generate_python(graph)


@pytest.mark.parametrize(
    ("ntype", "expected"),
    [
        ("qiskit.hadamard", "qc.h(3)"),
        ("qiskit.pauli_x", "qc.x(3)"),
        ("qiskit.pauli_y", "qc.y(3)"),
        ("qiskit.pauli_z", "qc.z(3)"),
    ],
)
def test_single_qubit_gates(ntype: str, expected: str) -> None:
    graph = {"nodes": [_node("g", ntype, qubit_index=3)], "config": {"num_qubits": 4}}
    assert expected in generate_python(graph)


def test_barrier_and_unknown_node_type() -> None:
    graph = {
        "nodes": [
            _node("b", "qiskit.barrier"),
            _node("u", "qiskit.not_a_gate"),
        ],
        "edges": [_edge("b", "u")],
    }
    script = generate_python(graph)
    assert "qc.barrier()" in script
    assert "# unknown node type: 'qiskit.not_a_gate'" in script


def test_plot_without_run_raises_at_runtime() -> None:
    script = generate_python({"nodes": [_node("p", "qiskit.plot_histogram")]})
    assert "raise RuntimeError('PlotHistogram requires a Run node upstream')" in script
    assert "_fig" not in script


@pytest.mark.parametrize(
    ("vtype", "raw", "expected"),
    [
        ("Int", "42", "x: int = 42"),
        ("Int", "", "x: int = 0"),
        ("Float", "", "x: float = 0.0"),
        ("Str", "FIAP", "x: str = 'FIAP'"),
        ("Str", '"quoted"', 'x: str = "quoted"'),
        ("Str", "", 'x: str = ""'),
        ("Bool", "Yes", "x: bool = True"),
        ("Bool", "0", "x: bool = False"),
        ("Bool", "not y", "x: bool = not y"),
        ("List", "[1, 2]", "x: list = [1, 2]"),
        ("Dict", "", "x: dict = {}"),
    ],
)
def test_variable_coercion(vtype: str, raw: str, expected: str) -> None:
    graph = {"variables": [{"name": "x", "type": vtype, "value": raw}]}
    assert expected in generate_python(graph).splitlines()


def test_user_defs_emitted_between_imports_and_circuit() -> None:
    graph = {
        "variables": [{"name": "n", "type": "Int", "value": "3"}],
        "functions": [
            {
                "name": "double",
                "return_type": "Int",
                "parameters": [{"name": "v", "type": "Int"}, {"name": "  "}],
                "body": "return v * 2\n\n",
            }
        ],
        "classes": [
            {
                "name": "Point",
                "parent_class": "object",
                "decorators": ["dataclass", ""],
                "variables": [{"name": "x", "type": "Float", "value": "1"}],
                "methods": [{"name": "norm", "return_type": "Float", "body": ""}],
            }
        ],
    }
    script = generate_python(graph)
    ast.parse(script)
    lines = script.splitlines()
    assert lines.index("n: int = 3") < lines.index("qc = QuantumCircuit(2, 2)")
    assert "def double(v: int) -> int:" in lines
    assert "    return v * 2" in lines
    assert "@dataclass" in lines
    assert "class Point(object):" in lines
    assert "    x: float = 1" in lines
    assert "    def norm(self) -> float:" in lines
    assert "        pass" in lines


def test_empty_class_gets_pass() -> None:
    script = generate_python({"classes": [{"name": "Empty"}]})
    ast.parse(script)
    assert "class Empty:" in script.splitlines()


def test_nameless_items_are_skipped() -> None:
    graph = {
        "variables": [{"name": "", "type": "Int"}],
        "functions": [{"name": "  "}],
        "classes": [{"name": None}],
    }
    assert generate_preamble(graph) == "# Variables\n\n# Functions\n\n# Classes"


def test_preamble_has_no_circuit() -> None:
    graph = {
        "nodes": [_node("h", "qiskit.hadamard")],
        "variables": [{"name": "k", "type": "Str", "value": "hi"}],
    }
    assert generate_preamble(graph) == "# Variables\nk: str = 'hi'"
    assert generate_preamble({}) == ""
